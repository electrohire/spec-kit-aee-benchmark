"""Tripwire records: every halt classified under the shared taxonomy,
and — since the 2026-10-21 stop-policy revision — the behavior that
classification drives.

Protocol amendment 2026-10-20, PC-4. A halt is classified as exactly
one of:

- ``model_outcome`` — the measured result of the model's own work:
  the AEE gate's recovery bound was exhausted, or a disclosed limit
  (wall time, call count, attempt token reservation) was reached.
- ``premise_equipment`` — the run's premises or equipment failed, or
  the operator stopped it: campaign budget, an operator interrupt, a
  missing prerequisite, an infrastructure or transport error.
- ``integrity`` — an identity or freeze fact did not check out: the
  solver image is not the clean base checkout, a freeze or resume
  configuration mismatch.
- ``unknown`` — anything else, including interrupted attempts whose
  cause was never established. Unknown is an honest class, not a
  rounding bucket: a halt whose cause is not established is never
  promoted into a model outcome.

Classification semantics are unchanged by the 2026-10-21 revision
(protocol PC-8): any recorded halt — including one written before
this module existed — classifies the same way. What the revision
changes is behavior. For an attempt that started, behavior follows
the classification: a proven model outcome stands as scored and the
schedule continues; a premise or equipment fault, an integrity
fault, or anything unknown halts the study. Each tripwire record
written under the revision names the behavior taken in its
``behavior`` field and carries ``behavior_changed: True``.

No new model_outcome kinds beyond those proven here: the only
proven model outcomes are the ones ``classify_halt`` maps there —
the AEE gate recovery bound exhausted, disclosed limits reached,
and, added by Amendment 1 (2026-10-21), phase-budget exhaustion.
Cycle 1 C1-A3 (2026-10-21) adds one more on the same basis: the
named ``call_outer_bound`` limit, generated by the transport's own
clocks when a demonstrably flowing call reaches the hard outer
bound, and recognized only via that exact protocol reason.
All are generated by the harness's own gate/accounting from the
calls ledger, which is the mechanical proof that the model's
requests reached the model intact. Phase-budget exhaustion is
generated by the harness's own phase accounting from the calls
ledger — the same mechanical-proof basis, because the budget
ledger is harness-side — and it is recognized ONLY via the
explicit protocol reason ``phase_budget_exhausted:<phase>``,
never via natural wording. Anything not established stays
unknown and halts.

Cycle 2 C2-F1 (2026-10-22) adds one more on the same basis: the
attempt wall expiring — including mid-call, where the harness
passes the wall remainder as the per-call deadline — is a scored
model outcome, recognized ONLY via the explicit protocol reason
``attempt_wall_expired``, through a classifier branch placed
BEFORE the generic transport rules below (the Amendment 1 note-1
lesson: never rely on reason wording — Cycle 1's fatal call died
under exactly that remainder deadline and its generic transport
wording classified it as an infrastructure halt). A wall expiry
that reaches the classifier under any other status, or under
natural wording, is NOT promoted by this branch. The stall
(600 s of silence, R-A5 bundle) and the 7,200 s per-call outer
bound keep their prior semantics unchanged.

The pre-start diagnostic pre-skip is excluded from the policy: it is
an admission decision before any attempt starts, not a halt. Its
record carries ``behavior: "skip_and_continue"`` and
``behavior_changed: False`` — the behavior it had before this
revision, unchanged.
"""
from .store import utc

MODEL_OUTCOME = "model_outcome"
PREMISE_EQUIPMENT = "premise_equipment"
INTEGRITY = "integrity"
UNKNOWN = "unknown"

SCORE_AND_CONTINUE = "score_and_continue"
HALT_STUDY = "halt_study"
SKIP_AND_CONTINUE = "skip_and_continue"

PHASE_BUDGET_EXHAUSTED = "phase_budget_exhausted"

# Cycle 2 C2-F1: the protocol reason token for an attempt-wall
# expiry (including a mid-call expiry under the wall-remainder
# per-call deadline). Scored as a model outcome; the patch is
# graded as it stands and the study proceeds to the next attempt.
ATTEMPT_WALL_EXPIRED = "attempt_wall_expired"


def phase_exhaustion_reason(phase):
    """The protocol reason token for a phase-budget exhaustion halt."""
    return f"{PHASE_BUDGET_EXHAUSTED}:{phase}"


def attempt_wall_expiry_reason():
    """The protocol reason token for an attempt-wall expiry halt."""
    return ATTEMPT_WALL_EXPIRED


_INTEGRITY_MARKERS = ("clean base checkout", "freeze", "resume configuration mismatch")
_PREMISE_MARKERS = ("docker", "image", "provider", "transport", "connection",
                    "sandbox", "patch extraction", "credential", "no usable temporary")


def classify_halt(status, reason):
    """Classify one attempt halt as (halt_class, halt_kind).

    ``status`` and ``reason`` are the run record's own values; the
    classification derives from them alone, so any recorded halt —
    including one written before this module existed — classifies
    the same way.
    """
    text = " ".join(str(reason or "").split())
    low = text.lower()
    # Cycle 2 C2-F1: the explicit attempt-wall-expiry branch, placed
    # before every generic rule in this classifier — in particular
    # before the generic transport rules in the "error" branch
    # below, whose markers ("provider", "transport", ...) are what
    # misclassified Cycle 1's wall-killed flowing call as an
    # infrastructure halt. The branch fires ONLY on the exact
    # protocol token under status "limit"; natural wording such as
    # "attempt wall expired" never reaches it.
    if status == "limit" and (
            low == ATTEMPT_WALL_EXPIRED
            or low.startswith(ATTEMPT_WALL_EXPIRED + ":")
            or low.startswith(ATTEMPT_WALL_EXPIRED + " ")):
        return MODEL_OUTCOME, ATTEMPT_WALL_EXPIRED
    if status == "limit":
        if (low == PHASE_BUDGET_EXHAUSTED
                or low.startswith(PHASE_BUDGET_EXHAUSTED + ":")
                or low.startswith(PHASE_BUDGET_EXHAUSTED + " ")):
            return MODEL_OUTCOME, PHASE_BUDGET_EXHAUSTED
        if low == "call_outer_bound" or low.startswith("call_outer_bound:"):
            # Cycle 1 C1-A3: a flowing call reached the hard outer
            # bound — a disclosed limit, generated by the harness's
            # own transport clocks, on the same mechanical-proof basis
            # as the other disclosed limits.
            return MODEL_OUTCOME, "call_outer_bound"
        if text == "AEE recovery bound":
            return MODEL_OUTCOME, "aee_gate_recovery_exhausted"
        if "budget" in low or "reservation would exceed cap" in low:
            return PREMISE_EQUIPMENT, "campaign_budget_exceeded"
        return MODEL_OUTCOME, "disclosed_limit_reached"
    if status == "cancelled":
        return PREMISE_EQUIPMENT, "operator_interrupt"
    if status == "infrastructure_failure":
        return UNKNOWN, "interrupted_attempt"
    if status == "skipped":
        return PREMISE_EQUIPMENT, "prerequisite_evidence_missing"
    if status == "error":
        if any(marker in low for marker in _INTEGRITY_MARKERS):
            return INTEGRITY, "identity_or_freeze_mismatch"
        if any(marker in low for marker in _PREMISE_MARKERS):
            return PREMISE_EQUIPMENT, "infrastructure_error"
        return UNKNOWN, "unclassified_error"
    return UNKNOWN, "unclassified_status"


def behavior_for(status, halt_class):
    """The behavior the stop policy assigns to one classified halt.

    A proven model outcome scores its attempt and the schedule
    continues; every other class halts the study. The pre-start
    pre-skip is excluded from the policy and continues, as before.
    """
    if status == "skipped":
        return SKIP_AND_CONTINUE
    if halt_class == MODEL_OUTCOME:
        return SCORE_AND_CONTINUE
    return HALT_STUDY


def record_tripwire(store, identity, status, reason):
    """Append the tripwire event for an attempt that ended other
    than completed. Returns the event, or None for a completion.

    The event names the behavior taken under the 2026-10-21
    revision in its ``behavior`` field; ``behavior_changed`` is
    True for records the revision governs (every halt of a started
    attempt) and False for the excluded pre-start pre-skip, whose
    behavior the revision does not change.
    """
    if status == "completed":
        return None
    halt_class, halt_kind = classify_halt(status, reason)
    event = {**identity, "status": status, "reason": reason,
             "halt_class": halt_class, "halt_kind": halt_kind,
             "behavior": behavior_for(status, halt_class),
             "behavior_changed": status != "skipped",
             "timestamp": utc()}
    store.append("tripwires", event)
    return event
